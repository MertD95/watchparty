import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { ACTION, ACTION_ROUTE } from './action-contract-source.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(__dirname, '..', 'extension', 'wp-actions.js');
const checkOnly = process.argv.includes('--check');

const actionKeys = Object.keys(ACTION);
const routeKeys = Object.keys(ACTION_ROUTE);

for (const key of actionKeys) {
  if (!Object.hasOwn(ACTION_ROUTE, key)) {
    throw new Error(`Missing ACTION_ROUTE entry for ${key}`);
  }
}

for (const key of routeKeys) {
  if (!Object.hasOwn(ACTION, key)) {
    throw new Error(`ACTION_ROUTE contains unknown action ${key}`);
  }
  const route = ACTION_ROUTE[key];
  if (!route || typeof route !== 'object') {
    throw new Error(`ACTION_ROUTE.${key} must be an object`);
  }
  if (!Array.isArray(route.sources) || route.sources.length === 0) {
    throw new Error(`ACTION_ROUTE.${key}.sources must be a non-empty array`);
  }
  if (typeof route.target !== 'string' || !route.target.trim()) {
    throw new Error(`ACTION_ROUTE.${key}.target must be a non-empty string`);
  }
}

const actionEntries = Object.entries(ACTION)
  .map(([key, value]) => `    ${key}: '${value}',`)
  .join('\n');

function renderRouteEntry(key, route) {
  const sources = route.sources.map((source) => `'${source}'`).join(', ');
  const optionalFlags = [
    route.requiresTrustedEvent === true ? '      requiresTrustedEvent: true,' : null,
    route.activeVideoOnly === true ? '      activeVideoOnly: true,' : null,
  ].filter(Boolean).join('\n');
  const flagsBlock = optionalFlags ? `\n${optionalFlags}` : '';
  return `    ${key}: Object.freeze({
      action: WPAction.${key},
      sources: Object.freeze([${sources}]),
      target: '${route.target}',${flagsBlock}
    }),`;
}

const routeEntries = Object.entries(ACTION_ROUTE)
  .map(([key, route]) => renderRouteEntry(key, route))
  .join('\n');

const output = `// AUTO-GENERATED by watchparty/tools/gen-action-contract.mjs
// Source of truth: watchparty/tools/action-contract-source.mjs
// Do not edit manually - run: node tools/gen-action-contract.mjs

const WPAction = (() => {
  'use strict';

  const ACTION = Object.freeze({
${actionEntries}
  });

  return ACTION;
})();

const WPActionRoutes = (() => {
  'use strict';

  return Object.freeze({
${routeEntries}
  });
})();

const WPActionContract = (() => {
  'use strict';

  const routesByAction = Object.freeze(
    Object.values(WPActionRoutes).reduce((routes, route) => {
      if (route?.action) routes[route.action] = route;
      return routes;
    }, {})
  );

  function getRoute(action) {
    return routesByAction[action] || null;
  }

  function isKnownAction(action) {
    return !!getRoute(action);
  }

  function isAllowedSource(action, source) {
    return getRoute(action)?.sources?.includes(source) === true;
  }

  function isTarget(action, target) {
    return getRoute(action)?.target === target;
  }

  function requiresTrustedEvent(action) {
    return getRoute(action)?.requiresTrustedEvent === true;
  }

  function isActiveVideoOnly(action) {
    return getRoute(action)?.activeVideoOnly === true;
  }

  function getActionsForTarget(target) {
    return Object.freeze(
      Object.values(WPActionRoutes)
        .filter((route) => route?.target === target)
        .map((route) => route.action)
    );
  }

  return Object.freeze({
    getRoute,
    isKnownAction,
    isAllowedSource,
    isTarget,
    requiresTrustedEvent,
    isActiveVideoOnly,
    getActionsForTarget,
  });
})();
`;

function normalizeNewlines(value) {
  return String(value || '').replace(/\r\n/g, '\n');
}

if (checkOnly) {
  const current = readFileSync(outputPath, 'utf8');
  if (normalizeNewlines(current) !== normalizeNewlines(output)) {
    console.error('wp-actions.js is out of date. Run: node tools/gen-action-contract.mjs');
    process.exit(1);
  }
  console.log('wp-actions.js is up-to-date.');
  process.exit(0);
}

writeFileSync(outputPath, output, 'utf8');
console.log(`Generated ${outputPath}`);
